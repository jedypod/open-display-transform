def generate(gen):
    nodes, n = [], gen.input(0)
    while n is not None and MARK not in n.knobs():
        nodes.append(n)
        n = n.input(0)
    if n is None:
        raise RuntimeError('No CLFShaper found upstream of %s' % gen.name())
    if not nodes:
        raise RuntimeError('Nothing between %s and %s to bake' % (n.name(), gen.name()))
    odt = []   # ODT nodes at the tail are written as exact process nodes, not baked
    for x in nodes:
        if ODT_MARK not in x.knobs() or x['disable'].value() or odt_ops(x, False) is None:
            break
        odt.append(x)
    if len(odt) == len(nodes):   # nothing else to bake: bake them
        odt = []
    for x in odt:
        x['disable'].setValue(True)
    try:
        bake_chain(gen, nodes, n, odt)
    finally:
        for x in odt:
            x['disable'].setValue(False)


def bake_chain(gen, nodes, shaper_node, odt):

    auto_note = ''
    log_input = bool(gen['log_input'].value())
    if gen['domain'].value() == 'auto':
        # Probe the chain: seven ramps (neutral, 3 chromatic, 3 single-channel
        # negative), find where the output stops changing by more than a 10-bit
        # step, and if that is beyond the shaper's top (or a bounded floor below its
        # floor), extend the lattice's code range to cover it with a stop of margin.
        # The curve stays the preset (T-LogE by default); measured equal to fitting
        # a new curve, and the file keeps one known encoding.
        sn = shaper_node
        sn['probe'].setValue(True)
        try:
            W, H, NX = gen.width(), gen.height(), 128
            xs = [(i + 0.5) * W / NX for i in range(NX)]

            def row(v):
                y = (v + 0.5) * H / 8
                return [[gen.sample(c, x, y) for c in ('red', 'green', 'blue')] for x in xs]

            def run_start(vals):
                eps = max(1.0, max(abs(c) for p in vals for c in p)) / 1023.0
                last, i = vals[-1], len(vals) - 1
                while i > 0 and max(abs(a - b) for a, b in zip(vals[i - 1], last)) <= eps:
                    i -= 1
                return i

            top, floor, unsat = 0.0, 0.0, []
            for v in range(4):
                i = run_start(row(v))
                if i >= NX - 1:
                    unsat.append('top')
                top = max(top, 0.18 * 2 ** (-20 + 44 * (i + 0.5) / NX))
            for v in range(4, 7):
                i = run_start(row(v))
                if i >= NX - 1:
                    unsat.append('floor')
                floor = min(floor, -0.18 * 2 ** (-20 + 26 * (i + 0.5) / NX))
        finally:
            sn['probe'].setValue(False)
        if 'top' in unsat:
            top = 2.0 ** 15
        gs, go, ls, lo, lb, sl = [sn[k].value() for k in ('gs', 'go', 'ls', 'lo', 'lb', 'sl')]
        logbreak = gs * math.log(ls * lb + lo, 2) + go

        def to_lin(code):
            return (code - (logbreak - sl * lb)) / sl if code <= logbreak else (2.0 ** ((code - go) / gs) - lo) / ls

        def to_code(lin):
            return sl * lin + (logbreak - sl * lb) if lin < lb else gs * math.log(ls * lin + lo, 2) + go

        # an unbounded floor (DRTs keep desaturating negatives forever) is not a reason to extend
        c1 = max(1.0, min(1.5, to_code(2.0 * top)))
        c0 = min(0.0, max(-0.1, to_code(2.0 * floor))) if 'floor' not in unsat else 0.0
        if top > to_lin(1.0) or c0 < 0.0:
            sn['code_min'].setValue(c0)
            sn['code_max'].setValue(c1)
            auto_note = ', auto: codes [%g, %g] (top %.4g)' % (c0, c1, top)
        else:
            sn['code_min'].setValue(0.0)
            sn['code_max'].setValue(1.0)
            auto_note = ', auto: %s covers it (top %.4g <= %.4g)' % (sn['preset'].value(), top, to_lin(1.0))
    shaper = dict((k, shaper_node[k].value()) for k in ('gs', 'go', 'ls', 'lo', 'lb', 'sl', 'w0', 'o', 'x0', 'y0', 'k',
                                                        'code_min', 'code_max'))
    shaper['preset'] = shaper_node['preset'].value()
    shaper['shortname'] = SHORT[int(shaper_node['preset'].getValue())]
    shaper['cube_size'] = int(shaper_node['cube_size'].value())
    shaper['legal_in'] = gen['levels'].value() in ('legal in', 'legal in and out')
    shaper['legal_out'] = gen['levels'].value() in ('legal out', 'legal in and out')

    # linear outputs: the cube stays code-to-code (best interpolation); exact decode
    # nodes after it reach lin_ciexyzd65 / lin_rec709 / lin_p3d65 display-referred
    decode, decode_note = None, ''
    drt_node = next((x for x in nodes if is_opendrt(x)), None)
    target = gen['output'].value()
    last = nodes[0]   # an ODT at the end sets the output, whether written as ops or baked (HLG)
    if ODT_MARK in last.knobs() and (odt or not last['disable'].value()):
        shaper['target'] = DISPLAYS[int(last['display'].getValue())][0].split(':')[-1]
        shaper['odt'] = True
        shaper['pq_fixed'] = gen['ocio'].value() == '2.4'
        if target != 'display codes':
            decode_note = ', the ODT node sets the output (output menu ignored)'
    elif target != 'display codes':
        if drt_node is None:
            decode_note = ', %s needs an OpenDRT node: display codes' % target
        elif drt_node['eotf'].value() == 'HLG':
            decode_note = ', HLG cannot be decoded (the node applies 20.5% of the inverse OOTF, not a standard operator): display codes'
        else:
            decode = dict(eotf=drt_node['eotf'].value(), gamut=drt_node['display_gamut'].value(),
                          lp=drt_node['tn_Lp'].value(), target=target, pq_fixed=(gen['ocio'].value() == '2.4'),
                          headroom=xyz_headroom(drt_node))
            shaper['target'] = target
    log_input = bool(gen['log_input'].value())

    path = gen['file'].evaluate()
    if not path:   # empty: next to the script (or the temp dir), named automatically
        root_name = nuke.root().name()
        path = os.path.dirname(root_name) if root_name and root_name != 'Root' else tempfile.gettempdir()

    # chain output for neutral 0.18 and 1.0 (probe row 7: left half grey, right half white)
    shaper_node['probe'].setValue(True)
    try:
        W, H = gen.width(), gen.height()
        measured = tuple([gen.sample(c, x, 7.5 * H / 8) for c in ('red', 'green', 'blue')] for x in (W * 0.25, W * 0.75))
    finally:
        shaper_node['probe'].setValue(False)
    shaper_node['pattern'].setValue(True)
    try:
        tmp = bake_cube(gen.node('GenerateLUT1'))
    finally:
        shaper_node['pattern'].setValue(False)
    size, path, pid = write_clf(path, tmp, shaper, nodes, gen['interpolation'].value(), log_input,
                                measured, bool(gen['embed_script'].value()), gen['format'].value(), decode,
                                list(reversed(odt)))
    os.remove(tmp)
    gen['file'].setValue(path)
    gen['status'].setValue('wrote %s (%d nodes, %d^3, %s%s)%s%s' % (
        os.path.basename(path), len(nodes), size, 'log input' if log_input else shaper['shortname'],
        ', -> ' + shaper['target'] if shaper.get('target') else '', auto_note, decode_note))


def from_clf(gen):
    parent = container(gen)
    nb = read_bake(gen['file'].evaluate())
    sc = nb.find('Script')
    if sc is None or not (sc.text or '').strip():
        raise RuntimeError('this CLF carries no node script (older bake); use Restore')
    shaper, n = None, gen.input(0)
    while n is not None:
        if MARK in n.knobs():
            shaper = n
            break
        n = n.input(0)
    if shaper is None:
        raise RuntimeError('connect a CLFShaper upstream of %s first; From CLF rebuilds the nodes between them' % gen.name())
    tmp = os.path.join(tempfile.gettempdir(), 'clfbake_from_%d.nk' % os.getpid())
    open(tmp, 'w').write(sc.text)
    with parent:
        for t in parent.nodes():
            t.setSelected(False)
        nuke.nodePaste(tmp)
        new = [t for t in parent.nodes() if t.isSelected()]
        for t in new:
            t.setSelected(False)
    os.remove(tmp)
    if not new:
        raise RuntimeError('nothing pasted from the CLF script')
    heads = [t for t in new if t.input(0) not in new]
    tails = [t for t in new if not any(d in new for d in t.dependent())]
    heads[0].setInput(0, shaper)
    gen.setInput(0, tails[0])
    for i, t in enumerate(new):
        t.setXYpos(gen.xpos(), gen.ypos() - 60 * (len(new) - i))
    done, sh = restore_apply(nb, [shaper])
    gen['domain'].setValue('preset')
    if sh is not None:
        gen['log_input'].setValue(sh.get('embedded') == 'false')
    gen['status'].setValue('from CLF: %s -> %s -> %s' % (shaper.name(), ' -> '.join(t.name() for t in new), gen.name()))


def restore(gen):
    nb = read_bake(gen['file'].evaluate())
    targets = [n for n in container(gen).nodes() if n.isSelected()]
    if not targets:
        n = gen.input(0)
        while n is not None:
            targets.append(n)
            if MARK in n.knobs():
                break
            n = n.input(0)
    done, sh = restore_apply(nb, targets)
    if sh is not None:
        gen['log_input'].setValue(sh.get('embedded') == 'false')
    gen['status'].setValue('restored: %s' % (', '.join(done) or 'nothing matched (select the nodes to restore)'))


# Thin buttons for OpenDRT.nk: fixed T-LogE shaper at 48^3, tetrahedral, embedded.
OPENDRT_SHAPER = dict(preset_params(0), preset=PRESETS[0][0], shortname=PRESETS[0][1], cube_size=48,
                      code_min=0.0, code_max=1.0, **dict(XLOG_DEFAULTS))
OPENDRT_SHAPER['logbreak'] = (OPENDRT_SHAPER['gs'] * math.log(OPENDRT_SHAPER['ls'] * OPENDRT_SHAPER['lb']
                              + OPENDRT_SHAPER['lo'], 2) + OPENDRT_SHAPER['go'])
OPENDRT_SHAPER['linoff'] = OPENDRT_SHAPER['logbreak'] - OPENDRT_SHAPER['sl'] * OPENDRT_SHAPER['lb']
OPENDRT_EXPR = [inverse_expr(c, OPENDRT_SHAPER) for c in 'rgb']


def opendrt_bake(n):
    path = n['clf_file'].evaluate()
    if not path:
        root_name = nuke.root().name()
        path = os.path.dirname(root_name) if root_name and root_name != 'Root' else tempfile.gettempdir()
    src = n.input(0)
    with container(n):
        pat = nuke.nodes.CMSTestPattern(cube_size=OPENDRT_SHAPER['cube_size'])
        inv = nuke.nodes.Expression(inputs=[pat], expr0=OPENDRT_EXPR[0], expr1=OPENDRT_EXPR[1], expr2=OPENDRT_EXPR[2])
        gw = nuke.nodes.Expression(expr0='x<width/2?0.18:1', expr1='x<width/2?0.18:1', expr2='x<width/2?0.18:1')
        lut = nuke.nodes.GenerateLUT(inputs=[n])
    try:
        n.setInput(0, gw)
        W, H = n.width(), n.height()
        measured = tuple([n.sample(c, x, H * 0.5) for c in ('red', 'green', 'blue')] for x in (W * 0.25, W * 0.75))
        n.setInput(0, inv)
        tmp = bake_cube(lut)
    finally:
        n.setInput(0, src)
        for t in (lut, gw, inv, pat):
            nuke.delete(t)
    size, path, pid = write_clf(path, tmp, OPENDRT_SHAPER, [n], 'tetrahedral', False, measured, True)
    os.remove(tmp)
    n['clf_file'].setValue(path)
    n['clf_params'].setValue(pid.split('clfbake{')[0])
    nuke.message('wrote %s' % path)


def opendrt_restore(n):
    done, sh = restore_apply(read_bake(n['clf_file'].evaluate()), [n])
    nuke.message('restored %s' % (', '.join(done) or 'nothing'))


def opendrt_apply(n):
    count = apply_params(n, n['clf_params'].value())
    nuke.message('applied %d parameters' % count)
